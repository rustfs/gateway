/// Appends, under `prefix`, `member` when the two lists differ in length, else every path at which two elements at the same index differ.
pub fn list<T>(prefix: &str, member: &str, left: &[T], right: &[T], out: &mut Vec<String>, each: fn(&str, &T, &T, &mut Vec<String>)) {
    if left.len() != right.len() {
        out.push(format!("{prefix}{member}"));
        return;
    }
    for (index, (l, r)) in left.iter().zip(right).enumerate() {
        each(&format!("{prefix}{member}[{index}]."), l, r, out);
    }
}

