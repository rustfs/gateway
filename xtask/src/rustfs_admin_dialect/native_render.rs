//! Generate the native host's two extension tables alongside the combined dialect.
//!
//! Responsible for: rendering `crates/dialect-rustfs-admin/src/native/extensions.rs` with separate
//! S3 and control-plane extension rows, folds, and shadowing declarations.
//! NOT responsible for: checking extension rows against legacy operations (`super::super::native`)
//! or declaring host-local admin claims and STS routes.
//! Upstream: `super::super::native`. Downstream: `super::super::native_pack`.

use std::fmt::Write as _;

use super::super::extension::Extended;

pub(in super::super) fn render_native_extensions(s3: &[Extended], control_plane: &[Extended], host_commit: &str) -> String {
    let license = super::LICENSE.split("// @generated").next().unwrap_or(super::LICENSE);
    let mut out = String::from(license);
    out.push_str("// @generated by `cargo xtask rustfs-admin-dialect` from the native host inventory.\n\n");
    out.push_str("//! S3 and control-plane extension registrations, each in its host table's order.\n");
    out.push_str("//!\n");
    out.push_str("//! Responsible for: declaring the native S3 and control-plane extension rows, folds, and\n");
    out.push_str("//! shadowing rules in their recorded host table order.\n");
    out.push_str("//! NOT responsible for: operation codecs (`crate::ops`), host control-plane claims, or STS.\n");
    out.push_str("//! Upstream: `crates/goldens/src/migration_inventory/rustfs_admin_routes_native.json`.\n");
    out.push_str("//! Downstream: `crate::native` and RustFS native S3 and control-plane listeners.\n\n");
    out.push_str("use rustfs_gateway_core::dialect::{DialectBuilder, DialectRoute};\nuse crate::admin::ExtensionOperation;\n\n");
    let _ = writeln!(
        out,
        "/// The host revision from which these registrations were collected.\npub const RUSTFS_SOURCE_COMMIT: &str = {host_commit:?};\n"
    );
    out.push_str(
        "/// A step over an operation and its route in one particular host table.\n\
         pub trait ExtensionRouteFold {\n\
         /// The value passed to the next operation.\n\
         type Carry;\n\
         /// Visits the existing operation type with the placement and overlaps of this host table.\n\
         fn step<O: ExtensionOperation>(&mut self, carry: Self::Carry, route: DialectRoute) -> Self::Carry;\n}\n",
    );
    out.push_str(
        "struct Declare;\n\
        impl ExtensionRouteFold for Declare {\n\
        type Carry = DialectBuilder;\n\
        fn step<O: ExtensionOperation>(&mut self, builder: DialectBuilder, route: DialectRoute) -> DialectBuilder {\n\
        builder.declare::<O>(route)\n}\n}\n",
    );
    table(&mut out, "s3", "Extensions registered on the S3 listener.", s3);
    table(
        &mut out,
        "control_plane",
        "Extensions registered alongside the host's control-plane claims.",
        control_plane,
    );
    out
}

fn table(out: &mut String, module: &str, doc: &str, rows: &[Extended]) {
    let _ = writeln!(out, "\n/// {doc}\npub mod {module} {{");
    out.push_str("use rustfs_gateway_core::dialect::OverlayRow;\n");
    if !rows.is_empty() {
        out.push_str("use crate::ops;\n");
    }
    for row in rows {
        operation(out, row);
    }
    out.push_str("\n/// The extension rows this listener contributes to its overlay.\npub static ROWS: &[OverlayRow] = &[\n");
    for row in rows {
        let _ = writeln!(out, "{}::ROW,", row.stem);
    }
    out.push_str("];\n\n/// Visits this listener's extension registrations in their recorded order.\n");
    out.push_str("pub fn fold<F: super::ExtensionRouteFold>(fold: &mut F, carry: F::Carry) -> F::Carry {\n");
    for (i, row) in rows.iter().enumerate() {
        let step = format!(
            "fold.step::<ops::{stem}::{ty}>(carry, {stem}::ROUTE)",
            stem = row.stem,
            ty = row.type_name
        );
        if i + 1 == rows.len() {
            let _ = writeln!(out, "{step}");
        } else {
            let _ = writeln!(out, "let carry = {step};");
        }
    }
    if rows.is_empty() {
        out.push_str("let _ = fold;\ncarry\n");
    }
    out.push_str(
        "}\n\n/// Declares this listener's extension rows on the supplied builder.\n\
        pub fn declare(builder: super::DialectBuilder) -> super::DialectBuilder {\n\
        fold(&mut super::Declare, builder)\n}\n}\n",
    );
}

fn operation(out: &mut String, row: &Extended) {
    let stem = &row.stem;
    let _ = writeln!(
        out,
        "\nmod {stem} {{\nuse crate::ops;\nuse rustfs_gateway_core::dialect::{{DialectRoute, OverlayRow}};"
    );
    let _ = writeln!(
        out,
        "pub(super) const ROW: OverlayRow = OverlayRow {{ precedence: {}, evidence: &[{:?}], ..ops::{stem}::OVERLAY_ROW }};",
        row.precedence, row.router_url
    );
    // Keep the source evidence with the winning row, and emit each reason once per operation.
    let mut reasons: Vec<&str> = Vec::new();
    if !row.shadows.is_empty() {
        out.push_str(
            "use rustfs_gateway_core::route::ShadowingDecl;\n\
             const fn shadows(shadowed: &'static str, reason: &'static str) -> ShadowingDecl {\n\
             ShadowingDecl { winner: ROW.name, shadowed, reason, evidence: ROW.evidence }\n}\n",
        );
    }
    let mut declarations = String::new();
    for shadowed in &row.shadows {
        let reason = match reasons.iter().position(|&reason| reason == shadowed.reason) {
            Some(i) => i,
            None => {
                let i = reasons.len();
                let _ = writeln!(out, "const REASON_{i}: &str = {:?};", shadowed.reason);
                reasons.push(&shadowed.reason);
                i
            }
        };
        let _ = writeln!(declarations, "shadows({:?}, REASON_{reason}),", shadowed.op);
    }
    let _ = writeln!(
        out,
        "pub(super) const ROUTE: DialectRoute = DialectRoute {{ precedence: ROW.precedence, shadows: &[\n{declarations}], ..ops::{stem}::ROUTE }};\n}}"
    );
}
