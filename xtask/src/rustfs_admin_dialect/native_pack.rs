//! Publish the native inventory as a sibling module of the frozen v1 dialect.
//!
//! Responsible for: comparing native route declarations against legacy v1 operations, sharing
//! unchanged operation types, and assembling the generated `native/{ops,rows,fold,extensions}.rs`
//! and `native/ops/*.rs` file map.
//! NOT responsible for: parsing the v2 inventory (`super::native`) or formatting and writing files
//! to disk (`super`).
//! Upstream: `super::native` and `super::render`. Downstream: `crates/dialect-rustfs-admin/src/native/`.

use std::collections::{BTreeMap, btree_map::Entry};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use super::{Declared, OUTPUT, Plan, extension::Extended, render};

pub(super) const INVENTORY: &str = "crates/goldens/src/migration_inventory/rustfs_admin_routes_native.json";

fn header(doc: &str, responsible: &str, not_responsible: &str, downstream: &str) -> String {
    let license = render::LICENSE.split("// @generated").next().unwrap_or(render::LICENSE);
    format!(
        "{license}// @generated by `cargo xtask rustfs-admin-dialect` from {INVENTORY}.\n\n\
         //! {doc}\n//!\n\
         //! Responsible for: {responsible}\n\
         //! NOT responsible for: {not_responsible}\n\
         //! Upstream: `{INVENTORY}` and `cargo xtask rustfs-admin-dialect`.\n\
         //! Downstream: {downstream}\n\n"
    )
}

/// These handlers ignore the payload, but the native control-plane listener has always read it
/// under its buffered size limit and checked its integrity before dispatch.
pub(super) fn buffers_unused_control_plane_body(d: &Declared) -> bool {
    d.request_body == "NotRead"
        && matches!(
            d.stem.as_str(),
            "delete_v3_bucket_etag_by_bucket"
                | "delete_v3_target_by_target_type_by_target_name"
                | "get_v3_bucket_etag_by_bucket"
                | "get_v3_site_replication_remove_v2_capabilities"
                | "get_v4_heal_mrf_cluster"
                | "get_v4_heal_mrf_cluster_responsibilities"
                | "get_v4_heal_mrf_cluster_responsibilities_by_node_id_by_id"
        )
}

/// Compare the generator's complete operation contract after accounting for the fields supplied by
/// the native table. A new handler body contract must never inherit the old operation's input type.
fn shares_operation(old: &mut Declared, new: &Declared, source: &str) -> bool {
    if buffers_unused_control_plane_body(new)
        || old.retained.is_some_and(|r| r.hand_on_body) != new.retained.is_some_and(|r| r.hand_on_body)
    {
        return false;
    }
    old.precedence = new.precedence;
    old.handler_url.clone_from(&new.handler_url);
    old.router_url.clone_from(&new.router_url);
    old.ruled.clone_from(&new.ruled);
    old.retained = new.retained;
    old.note = new.note;
    render::render_native_operation(old) == source
}

pub(super) fn files(
    plan: &Plan,
    legacy: Plan,
    s3: &[Extended],
    control: &[Extended],
    commit: &str,
) -> Result<BTreeMap<PathBuf, String>, String> {
    let dir = Path::new(OUTPUT).join("native");
    let mut files = BTreeMap::new();
    let mut previous: BTreeMap<_, _> = legacy.declared.into_iter().map(|d| (d.stem.clone(), d)).collect();
    let mut ops = header(
        "New and changed native operation types. Other operations retain their original types in `crate::ops`.",
        "mounting new or changed native operation modules, re-exporting shared `crate::ops` modules, and holding native evidence lists.",
        "declaring route placement (`super::rows`, `super::fold`) or backend execution.",
        "`super::rows`, `super::fold`, and RustFS native control-plane route registration.",
    );
    ops.push_str("pub(super) use crate::ops::*;\nuse crate::record;\n");
    let mut rows = header(
        "The native inventory's route records and overlay rows.",
        "exposing the native inventory's `ROUTES`, `PENDING`, `STAYING`, `FORM_ROUTES`, `RUSTFS_SOURCE_COMMIT`, and `OVERLAY_ROWS`.",
        "defining operation codecs (`super::ops`) or assembling the dialect (`super`).",
        "`super::OVERLAY`, `super::dialect`, and host inventory parity tests.",
    );
    rows.push_str("use super::ops;\nuse crate::record::{FormRouteRecord, PendingGroup, RouteRecord, StayingRoute};\n");
    rows.push_str("use rustfs_gateway_core::dialect::{FormRoute, OverlayRow};\nuse rustfs_gateway_core::route::FormClaim;\n");
    let _ = writeln!(
        rows,
        "/// The RustFS revision of the native inventory.\npub const RUSTFS_SOURCE_COMMIT: &str = {commit:?};"
    );
    render::render_inventory_lists(&mut rows, plan);
    let [form] = plan.forms.as_slice() else {
        return Err("native dialect requires one STS form".to_owned());
    };
    let [old_form] = legacy.forms.as_slice() else {
        return Err("legacy dialect requires one STS form".to_owned());
    };
    if form.handler != old_form.handler || form.caller_secret != old_form.caller_secret || form.group != old_form.group {
        return Err("native STS operation differs from the shared form type".to_owned());
    }
    let _ = writeln!(
        rows,
        "const STS_CLAIM: FormClaim = FormClaim {{ evidence: &[{:?}, {:?}], ..ops::sts_form_post::CLAIM }};",
        form.layer_url, form.router_url
    );
    rows.push_str("pub(super) const STS_ROUTE: FormRoute = FormRoute { claim: &STS_CLAIM, ..ops::sts_form_post::ROUTE };\n");
    let _ = writeln!(
        rows,
        "const STS_ROW: OverlayRow = OverlayRow {{ evidence: &[{:?}, {:?}, {:?}, crate::record::ISSUE], ..ops::sts_form_post::OVERLAY_ROW }};",
        form.handler_url,
        super::form::EVIDENCE,
        super::form::AUTH_EVIDENCE
    );

    let mut registrations = String::new();
    let mut fold = header(
        "The typed walk over the native inventory's claimed operations.",
        "providing `fold_every_operation` over every claimed native admin route in recorded precedence order.",
        "defining operation types (`super::ops`) or declaring fallback and STS routes (`super::dialect`).",
        "`super::dialect` and typed host operation registration.",
    );
    fold.push_str(
        "use super::{ops, OperationFold};\nuse crate::AdminOperation;\nuse rustfs_gateway_core::dialect::ClaimedRoute;\n",
    );
    fold.push_str("use rustfs_gateway_core::route::ShadowingDecl;\n");
    fold.push_str("fn visit<F: OperationFold, O: AdminOperation>(fold: &mut F, carry: F::Carry, precedence: u16, shadows: &'static [ShadowingDecl]) -> F::Carry { fold.step::<O>(carry, ClaimedRoute {precedence, rows: O::rows(), shadows, bucket_param: O::BUCKET}) }\n");
    fold.push_str(
        r#"macro_rules! operations {
        (@shadows $op:ty) => { <$op>::shadows() };
        (@shadows $op:ty, $native:ident) => { ops::$native };
        ($(($module:ident, $ty:ident, $precedence:literal $(, $native:ident)?)),* $(,)?) => {
            /// Visits each claimed operation with the native table's placement.
            pub fn fold_every_operation<F: OperationFold>(fold: &mut F, carry: F::Carry) -> F::Carry {
                $(let carry = visit::<F, ops::$module::$ty>(fold, carry, $precedence,
                    operations!(@shadows ops::$module::$ty $(, $native)?));)*
                carry
            }
        };
    }
    operations! {
"#,
    );
    let mut evidence_ids = BTreeMap::new();
    let mut evidence = String::new();
    for d in &plan.declared {
        let stem = &d.stem;
        let ty = &d.type_name;
        let rendered = render::render_native_operation(d);
        let old = previous.get_mut(stem);
        let mut record = format!("ops::{stem}::RECORD");
        let mut shadows = String::new();
        let mut share = false;
        if let Some(old) = old {
            let retained = |d: &Declared| d.retained.map_or(&[][..], |r| r.checks);
            let changed = old.ruled != d.ruled || retained(old) != retained(d);
            share = shares_operation(old, d, &rendered);
            if share && changed {
                let name = format!("{}_RECORD", stem.to_uppercase());
                let _ = writeln!(
                    rows,
                    "const {name}: RouteRecord = RouteRecord {{ ruled: {:?}, retained: &{:?}, ..ops::{stem}::RECORD }};",
                    d.ruled.as_deref(),
                    retained(d)
                );
                record = name;
            }
        }
        if share && !d.shadows.is_empty() {
            // Literal-template overlaps cite the native router. Authenticated fallback overlaps
            // that follow them retain their original ADR evidence.
            let name = format!("{}_SHADOWS", stem.to_uppercase());
            let _ = writeln!(ops, "pub(super) const {name}: &[rustfs_gateway_core::route::ShadowingDecl] = &[");
            for i in 0..d.shadows.len() {
                let more = if d.path.starts_with("/_iceberg/") {
                    ", record::ADR_0031"
                } else {
                    ""
                };
                let _ = writeln!(
                    ops,
                    "rustfs_gateway_core::route::ShadowingDecl {{ evidence: &[{:?},record::ADR_0027{more}], ..{stem}::SHADOWS[{i}] }},",
                    d.router_url
                );
            }
            for i in d.shadows.len()..d.shadows.len() + super::fallback::shadowed_by(d).count() {
                let _ = writeln!(ops, "{stem}::SHADOWS[{i}],");
            }
            ops.push_str("];\n");
            shadows = format!(", {name}");
        }
        if !share {
            let _ = writeln!(ops, "pub mod {stem};");
            let source = rendered
                .strip_prefix(render::LICENSE)
                .ok_or("missing generated operation header")?;
            let license = render::LICENSE.split("// @generated").next().unwrap_or(render::LICENSE);
            files.insert(
                dir.join("ops").join(format!("{stem}.rs")),
                format!("{license}// @generated by `cargo xtask rustfs-admin-dialect` from {INVENTORY}.\n\n{source}"),
            );
        }
        let sources = render::evidence(d);
        let index = evidence_ids.len();
        let id = match evidence_ids.entry(sources) {
            Entry::Occupied(found) => *found.get(),
            Entry::Vacant(slot) => {
                let _ = writeln!(evidence, "{},", slot.key());
                slot.insert(index);
                index
            }
        };
        let _ = writeln!(registrations, "({stem}, {}, {id}, {record}),", d.precedence);
        let _ = writeln!(fold, "({stem}, {ty}, {}{shadows}),", d.precedence);
    }
    fold.push_str("}\n");
    let _ = writeln!(ops, "pub(super) static EVIDENCE: &[&[&str]] = &[\n{evidence}];");
    rows.push_str(
        "macro_rules! registrations { ($(($op:ident, $precedence:literal, $evidence:literal, $record:expr)),* $(,)?) => {\n\
        /// Every claimed route as recorded in the native inventory.\n\
        pub static ROUTES: &[RouteRecord] = &[$($record),*];\n\
        pub(super) static OVERLAY_ROWS: &[OverlayRow] = &[\n\
        $(OverlayRow { precedence: $precedence, evidence: ops::EVIDENCE[$evidence], ..ops::$op::OVERLAY_ROW },)*\n\
        ops::admin_v4_fallback::OVERLAY_ROW, ops::admin_fallback::OVERLAY_ROW, STS_ROW,\n\
        ];\n }; }\nregistrations! {\n",
    );
    rows.push_str(&registrations);
    rows.push_str("}\n");
    for (path, text) in [
        ("rows.rs", rows),
        ("fold.rs", fold),
        ("ops.rs", ops),
        ("extensions.rs", render::render_native_extensions(s3, control, commit)),
    ] {
        files.insert(dir.join(path), text);
    }
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::super::tests::recorded_plan;
    use super::*;

    fn password() -> Declared {
        recorded_plan()
            .declared
            .into_iter()
            .find(|d| d.stem == "post_v3_account_password")
            .expect("password route")
    }

    #[test]
    fn native_control_plane_buffers_unused_payloads_before_dispatch() {
        let root = super::super::repo_root();
        let inventory = std::fs::read_to_string(root.join(INVENTORY)).expect("native inventory");
        let files = super::super::native::generate(&root, &inventory, true).expect("native dialect");
        let mut buffered_unit = Vec::new();
        for (path, source) in files {
            if source.contains("admin::buffered(body).map(drop)") {
                assert!(source.contains("type Input = ();"), "{}", path.display());
                assert!(source.contains("RequestBodyMode::Full;"), "{}", path.display());
                assert!(source.contains("request_body: BodyKind::NotRead,"), "{}", path.display());
                buffered_unit.push(path.file_stem().expect("operation file").to_string_lossy().into_owned());
            }
        }
        assert_eq!(
            buffered_unit,
            [
                "delete_v3_bucket_etag_by_bucket",
                "delete_v3_target_by_target_type_by_target_name",
                "get_v3_bucket_etag_by_bucket",
                "get_v3_site_replication_remove_v2_capabilities",
                "get_v4_heal_mrf_cluster",
                "get_v4_heal_mrf_cluster_responsibilities",
                "get_v4_heal_mrf_cluster_responsibilities_by_node_id_by_id",
            ]
        );
    }

    #[test]
    fn buffered_unit_handoff_is_native_and_limited_to_migrated_routes() {
        let mut route = password();
        route.stem = "get_v4_heal_mrf_cluster".to_owned();
        route.request_body = "NotRead";
        assert!(render::render_operation(&route).contains("RequestBodyMode::None;"));
        let mut old = password();
        old.stem.clone_from(&route.stem);
        old.request_body = route.request_body;
        assert!(!shares_operation(&mut old, &route, &render::render_native_operation(&route)));
        route.stem = "get_v4_future".to_owned();
        assert!(render::render_native_operation(&route).contains("RequestBodyMode::None;"));
    }

    #[test]
    fn a_new_placement_and_source_can_share_the_original_type() {
        let old = &mut password();
        let mut current = password();
        current.precedence += 9;
        current.handler_url.push_str("#current");
        assert!(shares_operation(old, &current, &render::render_native_operation(&current)));
    }

    #[test]
    fn codec_floor_and_selector_changes_require_a_native_type() {
        let current = password();
        let source = render::render_native_operation(&current);
        let mut old = password();
        old.caller_secret = !old.caller_secret;
        assert!(!shares_operation(&mut old, &current, &source));
        let mut old = password();
        old.rule.anonymous = !old.rule.anonymous;
        assert!(!shares_operation(&mut old, &current, &source));
        let mut old = password();
        old.alias = None;
        assert!(!shares_operation(&mut old, &current, &source));
        let check = super::super::rulings::native_retained()
            .into_iter()
            .find(|r| r.path == current.path)
            .expect("retained body check");
        let mut old = password();
        old.retained = Some(check);
        assert!(!shares_operation(&mut old, &current, &source));
    }
}
