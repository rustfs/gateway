    "a member only the legacy decoder reads and no gateway member holds, refused rather than dropped";

/// What a backward conversion does with a member only the legacy decoder reads
/// ([`Rule::FromQuery`], [`Rule::FromBoolHeader`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum LegacyMembers {
    /// Refused when set: a shape or output with no side channel.
    Refuse,
    /// Bound and handed back beside the gateway value as the operation's `LegacyInput`, for the
    /// ported use case to apply as the legacy stack did (rustfs/backlog#2749).
    HandBack,
}

/// The members of `s3s` only the legacy decoder reads, in declaration order.
pub(super) fn legacy_members<'s>(owner: &str, s3s: &'s [(String, S3sType)]) -> Vec<(&'s str, &'s S3sType)> {
    s3s.iter()
        .filter(|(member, _)| matches!(member_rule(owner, member), Some(Rule::FromQuery(_) | Rule::FromBoolHeader(_))))
        .map(|(member, ty)| (member.as_str(), ty))
        .collect()
}

/// The Rust spelling of a legacy-only member's s3s type, for the `LegacyInput` struct.
pub(super) fn type_text(ty: &S3sType) -> Result<String, String> {
    Ok(match ty {
        S3sType::Option(inner) => format!("Option<{}>", type_text(inner)?),
        S3sType::Leaf(leaf) if ["String", "bool", "i32", "i64"].contains(&leaf.as_str()) => leaf.clone(),
        other => return Err(format!("no `LegacyInput` spelling for {other:?}")),
    })
}

