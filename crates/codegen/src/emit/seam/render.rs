/// Whether `owner`'s member `field` is a container both sides hold bare: a list whose presence is
/// carried (`emit::dto::presence`) crosses as the `Option` it is on both sides instead.
fn is_bare_container(owner: &str, field: &Field) -> bool {
    is_container(&field.ty) && !crate::emit::dto::presence::carries_presence(owner, field)
}

pub(super) fn missing(field: &str, reason: &str) -> String {
    format!("return Err(ConversionError {{ field: \"{field}\", reason: \"{reason}\" }})")
}

/// Whether an empty value of this gateway member is absent on the legacy side: the legacy decoder
/// reads an optional header whose value is empty as no value at all, before parsing it, so a
/// textual header member the gateway holds as `Some("")` crosses as `None` (rustfs/gateway#1076).
fn empty_is_absent(field: &Field) -> bool {
    field.binding == Binding::Header
        && !field.required
        && matches!(field.ty, Type::String | Type::OpaqueString | Type::StringEnum(_) | Type::Range)
        && !crate::emit::dto::registry::is_secret_string_field(field)
}

/// The parameter a conversion takes when a legacy-only member is decoded from the raw request.
const WIRE_PARAMETER: (&str, &str) = ("wire", "&leaf::RequestWire<'_>");

/// Whose value a forward conversion builds: the legacy decoder's input, which read an empty
/// optional header as absent, or the legacy writer's output, which writes what it is given.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Forward {
    /// An s3s input, as the legacy decoder would have handed it over.
    Input,
    /// An s3s output, as the legacy writer takes it.
    Output,
}

/// Nested parents: (s3s member, nested struct, nested members with their values).
pub(super) type NestedParents<'s> = Vec<(&'s str, &'s str, Vec<(&'s str, String)>)>;

/// The s3s struct literal for the gateway value `src` of a struct with `fields`, read as the
