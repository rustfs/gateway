//! `spec/operations/<Op>.toml`: the field-binding view of one operation.
//!
//! Responsible for: the artefact an agent reads when it needs a field's wire name, binding, type,
//! optionality or quirk references — the answer that would otherwise require opening the model.
//! NOT responsible for: the operation-shape overview, which is `OPERATIONS.md`.
//! Upstream: [`rustfs_gateway_model::ir`]. Downstream: humans and agents; never parsed back.

use std::fmt::Write as _;

use rustfs_gateway_model::ir::*;

use super::{quote, string_list};

/// Renders one operation's spec file.
pub fn render(ir: &OperationIr) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# @generated by `cargo xtask codegen`. Do not edit: change `overlays/` and regenerate.\n\
         # Field bindings for one S3 operation. Operation shapes and the wire reverse index live\n\
         # in OPERATIONS.md.\n"
    );

    let _ = writeln!(out, "[operation]");
    let _ = writeln!(out, "name = {}", quote(&ir.operation));
    let _ = writeln!(out, "method = {}", quote(ir.http.method.as_str()));
    let _ = writeln!(out, "target = {}", quote(ir.http.target.as_str()));
    let _ = writeln!(out, "path_shape = {}", quote(&ir.http.path_shape));
    let _ = writeln!(out, "precedence = {}", ir.http.precedence);
    let _ = writeln!(out, "success_status = {}", ir.http.success_status);
    let _ = writeln!(
        out,
        "alt_success_statuses = [{}]",
        ir.http
            .alt_success_statuses
            .iter()
            .map(u16::to_string)
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(out, "predicates = {}", string_list(&predicates(ir)));
    if let Some(mirror) = &ir.head_mirrors {
        let _ = writeln!(out, "head_mirrors = {}", quote(mirror));
    }
    let _ = writeln!(out, "quirks = {}", string_list(&ir.quirk_refs));

    let _ = writeln!(out, "\n[auth]");
    let _ = writeln!(out, "requirement = {}", quote(ir.auth.requirement.as_str()));
    let _ = writeln!(out, "action = {}", quote(&ir.auth.action));
    let _ = writeln!(out, "presigned_allowed = {}", ir.auth.presigned_allowed);
    let _ = writeln!(out, "service = {}", quote(&ir.auth.service));

    let _ = writeln!(out, "\n[payload.request]");
    payload(&mut out, &ir.payload.request);
    let _ = writeln!(out, "\n[payload.response]");
    payload(&mut out, &ir.payload.response);

    let _ = writeln!(out, "\n[checksum]");
    let _ = writeln!(out, "http_checksum_required = {}", ir.checksum.http_checksum_required);
    let _ = writeln!(
        out,
        "request_algorithms = {}",
        string_list(
            &ir.checksum
                .request_algorithms
                .iter()
                .map(|a| a.as_str().to_owned())
                .collect::<Vec<_>>()
        )
    );
    let _ = writeln!(
        out,
        "response_algorithms = {}",
        string_list(
            &ir.checksum
                .response_algorithms
                .iter()
                .map(|a| a.as_str().to_owned())
                .collect::<Vec<_>>()
        )
    );

    let _ = writeln!(out, "\n[xml]");
    let _ = writeln!(out, "request_root = {}", quote(ir.xml.request_root.as_deref().unwrap_or("")));
    let _ = writeln!(out, "request_root_aliases = {}", string_list(&ir.xml.request_root_aliases));
    let _ = writeln!(out, "response_root = {}", quote(ir.xml.response_root.as_deref().unwrap_or("")));
    let _ = writeln!(out, "xmlns = {}", quote(ir.xml.xmlns.as_str()));
    let _ = writeln!(out, "unwrapped_output = {}", ir.xml.unwrapped_output);
    let _ = writeln!(out, "body_literal = {}", ir.xml.body_literal);
    let _ = writeln!(out, "element_order = {}", string_list(&ir.xml.element_order));
    let _ = writeln!(out, "url_encoded_fields = {}", string_list(&ir.xml.url_encoded_fields));
    if !ir.xml.empty_value_policy.is_empty() {
        let _ = writeln!(out, "\n[xml.empty_value]");
        for (name, policy) in &ir.xml.empty_value_policy {
            let _ = writeln!(out, "{name} = {}", quote(policy.as_str()));
        }
    }

    let _ = writeln!(out, "\n[errors]");
    let _ = writeln!(out, "not_configured = {}", quote(ir.errors.not_configured.as_deref().unwrap_or("")));
    let _ = writeln!(out, "allows_error_after_200 = {}", ir.errors.allows_error_after_200);
    let _ = writeln!(out, "codes = {}", string_list(&ir.errors.codes));

    for resource in &ir.derived_resources {
        let _ = writeln!(out, "\n[[derived_resource]]");
        let _ = writeln!(out, "name = {}", quote(&resource.name));
        let _ = writeln!(out, "source_field = {}", quote(&resource.source_field));
        let _ = writeln!(out, "kind = {}", quote(&resource.kind));
        let _ = writeln!(out, "action = {}", quote(&resource.action));
        let _ = writeln!(out, "required = {}", resource.required);
    }

    for field in &ir.input {
        let _ = writeln!(out, "\n[[input]]");
        render_field(&mut out, field);
    }
    for field in &ir.output {
        let _ = writeln!(out, "\n[[output]]");
        render_field(&mut out, field);
    }
    for (name, shape) in &ir.shapes {
        let _ = writeln!(out, "\n[shape.{name}]");
        let _ = writeln!(out, "kind = {}", quote(shape.kind.as_str()));
        let _ = writeln!(out, "element_order = {}", string_list(&shape.xml.element_order));
        if !shape.xml.empty_value_policy.is_empty() {
            let _ = writeln!(out, "\n[shape.{name}.empty_value]");
            for (member, policy) in &shape.xml.empty_value_policy {
                let _ = writeln!(out, "{member} = {}", quote(policy.as_str()));
            }
        }
        for attribute in &shape.xml.attributes {
            let _ = writeln!(out, "\n[[shape.{name}.attribute]]");
            let _ = writeln!(out, "element = {}", quote(&attribute.element));
            let _ = writeln!(out, "name = {}", quote(&attribute.name));
            match &attribute.source {
                AttributeSource::Field(member) => {
                    let _ = writeln!(out, "source = \"field\"");
                    let _ = writeln!(out, "field = {}", quote(member));
                }
                AttributeSource::Constant(literal) => {
                    let _ = writeln!(out, "source = \"constant\"");
                    let _ = writeln!(out, "value = {}", quote(literal));
                }
            }
        }
        for field in &shape.fields {
            let _ = writeln!(out, "\n[[shape.{name}.field]]");
            render_field(&mut out, field);
        }
    }
    out
}

fn payload(out: &mut String, spec: &PayloadSpec) {
    let _ = writeln!(out, "kind = {}", quote(spec.kind.as_str()));
    let _ = writeln!(out, "buffering = {}", quote(spec.buffering.as_str()));
    match spec.max_bytes {
        Some(n) => {
            let _ = writeln!(out, "max_bytes = {n}");
        }
        None => {
            let _ = writeln!(out, "# max_bytes: unbounded");
        }
    }
}

fn render_field(out: &mut String, field: &Field) {
    let _ = writeln!(out, "name = {}", quote(&field.name));
    let _ = writeln!(out, "wire_name = {}", quote(field.wire_name.as_deref().unwrap_or("")));
    let _ = writeln!(out, "binding = {}", quote(&binding(&field.binding)));
    let _ = writeln!(out, "type = {}", quote(&type_name(&field.ty)));
    let _ = writeln!(out, "required = {}", field.required);
    let _ = writeln!(out, "hot = {}", field.hot);
    if let Some(default) = &field.default {
        let _ = writeln!(out, "default = {}", super::json_scalar(default));
    }
    if let Some(omit) = &field.omit_when {
        let _ = writeln!(out, "omit_when = {}", quote(&omit_when(omit)));
    }
    if let Some(code) = &field.missing_error {
        let _ = writeln!(out, "missing_error = {}", quote(code));
    }
    if let Type::StringEnum(values) = &field.ty {
        let _ = writeln!(out, "values = {}", string_list(values));
    }
    let _ = writeln!(out, "quirks = {}", string_list(&field.quirk_refs));
}

fn binding(binding: &Binding) -> String {
    match binding {
        Binding::UriLabel { greedy: true } => "UriLabel(greedy)".to_owned(),
        other => other.kind_str().to_owned(),
    }
}

fn omit_when(omit: &OmitWhen) -> String {
    match omit {
        OmitWhen::Empty => "Empty".to_owned(),
        OmitWhen::Default => "Default".to_owned(),
        OmitWhen::ValueEquals(v) => format!("ValueEquals({v})"),
        OmitWhen::RequestField { field, equals } => format!("RequestField({field}=={equals})"),
    }
}

/// A one-line spelling of an IR type, stable enough to diff.
pub fn type_name(ty: &Type) -> String {
    match ty {
        Type::String => "String".into(),
        Type::OpaqueString => "OpaqueString".into(),
        Type::Integer => "Integer".into(),
        Type::Long => "Long".into(),
        Type::Boolean => "Boolean".into(),
        Type::Timestamp(f) => format!("Timestamp({})", f.as_str()),
        Type::ETag(r) => format!("ETag({})", r.as_str()),
        Type::Checksum(a) => format!("Checksum({})", a.as_str()),
        Type::ChecksumSpec => "ChecksumSpec".into(),
        Type::ObjectKey => "ObjectKey".into(),
        Type::BucketName => "BucketName".into(),
        Type::Range => "Range".into(),
        Type::Capability { exchange } => format!("Capability({exchange})"),
        Type::StringEnum(_) => "StringEnum".into(),
        Type::Structure(name) => format!("Structure({name})"),
        Type::Union(name) => format!("Union({name})"),
        Type::List {
            member,
            flattened,
            member_name,
        } => {
            let shape = match (flattened, member_name.as_deref()) {
                (true, _) => "flattened",
                (false, Some(entry)) => entry,
                (false, None) => "delimited",
            };
            format!("List<{}>({shape})", type_name(member))
        }
        Type::Map { key, value } => format!("Map<{}, {}>", type_name(key), type_name(value)),
        Type::Blob { streaming: true } => "Blob(streaming)".into(),
        Type::Blob { streaming: false } => "Blob".into(),
    }
}

/// The human-readable spelling of the route predicates, used by both emitters.
pub fn predicates(ir: &OperationIr) -> Vec<String> {
    ir.http.predicates.iter().map(predicate).collect()
}

/// One predicate as a single line.
pub fn predicate(p: &Predicate) -> String {
    match p {
        Predicate::Method(m) => format!("Method {}", m.as_str()),
        Predicate::Target(t) => format!("Target {}", t.as_str()),
        Predicate::QueryPresent(k) => format!("QueryPresent ?{k}"),
        Predicate::QueryEquals(k, v) => format!("QueryEquals ?{k}={v}"),
        Predicate::QueryAbsent(k) => format!("QueryAbsent ?{k}"),
        Predicate::HeaderPresent { header, negated: false } => format!("HeaderPresent {header}"),
        Predicate::HeaderPresent { header, negated: true } => format!("HeaderAbsent {header}"),
        Predicate::HeaderPrefix { header, prefix } => format!("HeaderPrefix {header}: {prefix}"),
        Predicate::PathLiteral(path) => format!("PathLiteral {path}"),
        Predicate::HostClass(class) => format!("HostClass {}", class.as_str()),
        Predicate::ArnForm(form) => format!("ArnForm {}", form.as_str()),
    }
}

#[cfg(test)]
mod tests {
    use super::predicate;
    use rustfs_gateway_model::ir::{ArnForm, HostClass, Predicate};

    #[test]
    fn renders_host_class_and_arn_form_predicates() {
        assert_eq!(predicate(&Predicate::HostClass(HostClass::S3Express)), "HostClass S3Express");
        assert_eq!(predicate(&Predicate::ArnForm(ArnForm::Mrap)), "ArnForm MRAP");
    }
}
