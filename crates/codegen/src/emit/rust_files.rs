//! The Rust data artefacts consumed by runtime and proc-macro crates.
//!
//! Responsible for: `routes.rs` (the ordered first-match route table) and `error_codes.rs` (the
//! error code to operation index) under `generated/`, plus the proc-macro operation-name table.
//! NOT responsible for: defining the types they mention. The route and error files are `include!`
//! fodder for the crate that owns `RouteRow`, `RoutePredicate` and `ErrorCodeRow` (P4); a generated
//! file that minted its own public type names would put names into the tree that `grep` cannot
//! trace back to a hand-written declaration.
//! Upstream: [`rustfs_gateway_model::ir`]. Downstream: P4's route table.
//!
//! No AWS prose is copied into either file: the only English in them is written here.

