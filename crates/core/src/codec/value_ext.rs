//! Extended codec scalar bounds and request-field omission predicates.
//!
//! Responsible for: range-checked integer parsing with an operation-specific error code, 64-bit
//! range-checked integer parsing, and request query/header equality predicates used by XML
//! `omit_when` guards.
//! NOT responsible for: choosing which operation member carries which bound or omission rule
//! (generated by `rustfs-gateway-codegen`).
//! Upstream: `crate::codec::value`, `crate::codec::view::MetaView`. Downstream: generated codecs.

use rustfs_gateway_types::ErrorCode;

use crate::codec::document::DocumentReading;
use crate::codec::error::CodecError;
use crate::codec::value::{integer, integer_in_range, long, unusable};
use crate::codec::view::MetaView;

/// Parses a 32-bit integer inside `[min, max]` under [`DocumentReading::Tree`], leaving range
/// checks to legacy RustFS handlers under [`DocumentReading::RustFs`].
///
/// # Errors
///
/// [`CodecError`] naming the member.
pub fn tree_integer_in_range(
    value: &str,
    member: &'static str,
    min: i32,
    max: i32,
    reading: DocumentReading,
) -> Result<i32, CodecError> {
    if reading == DocumentReading::RustFs {
        return integer(value, member);
    }
    integer_in_range(value, member, min, max)
}

/// Parses a 32-bit integer and refuses one outside `[min, max]` with the caller-supplied S3 error code.
///
/// Unparseable syntax remains `InvalidArgument` (through [`integer`]); an in-syntax integer outside
/// the protocol range reports `code` (for example `InvalidPartNumber` on `GetObject`/`HeadObject`).
///
/// # Errors
///
/// [`CodecError`] naming the member.
pub fn integer_in_range_as(value: &str, member: &'static str, min: i32, max: i32, code: ErrorCode) -> Result<i32, CodecError> {
    let parsed = integer(value, member)?;
    if parsed < min || parsed > max {
        return Err(CodecError::new(code, "the request carries a value this member cannot hold").about(member));
    }
    Ok(parsed)
}

/// Parses a 64-bit integer and refuses one outside `[min, max]`.
///
/// # Errors
///
/// [`CodecError`] naming the member.
pub fn long_in_range(value: &str, member: &'static str, min: i64, max: i64) -> Result<i64, CodecError> {
    let parsed = long(value, member)?;
    if parsed < min || parsed > max {
        return Err(unusable(member));
    }
    Ok(parsed)
}

/// Whether a boolean query parameter on `request` (falling back to `default` when absent or
/// unparseable) equals `target`.
#[must_use]
pub fn request_query_equals_bool(request: &MetaView<'_>, key: &str, default: bool, target: bool) -> bool {
    let actual = match request.query(key) {
        Ok(Some(raw)) if raw.as_ref().eq_ignore_ascii_case("true") => true,
        Ok(Some(raw)) if raw.as_ref().eq_ignore_ascii_case("false") => false,
        _ => default,
    };
    actual == target
}

/// Whether a string query parameter on `request` (falling back to `default` when absent) equals
/// `target`.
#[must_use]
pub fn request_query_equals(request: &MetaView<'_>, key: &str, default: Option<&str>, target: &str) -> bool {
    match request.query(key) {
        Ok(Some(raw)) => raw.as_ref() == target,
        _ => default == Some(target),
    }
}

/// Whether a header on `request` (falling back to `default` when absent) equals `target`.
#[must_use]
pub fn request_header_equals(request: &MetaView<'_>, key: &str, default: Option<&str>, target: &str) -> bool {
    match request.header(key) {
        Some(raw) => raw.as_ref() == target,
        None => default == Some(target),
    }
}
