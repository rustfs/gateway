//! Typed Select response parity, producer lifetime, and framing refusals.
//!
//! Responsible for: measured bytes and the observable lazy-stream contract through the codec.
//! NOT responsible for: query execution or the separate manual EventSequence contract.
//! Upstream: owned producers and independent public-API oracle measurements. Downstream: nothing.

#![allow(clippy::expect_used, clippy::panic)]

use std::cell::Cell;
use std::collections::VecDeque;
use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::task::Waker;

use rustfs_gateway_http::{Limits, WireRequest};
use rustfs_gateway_types::dto;

use super::*;
use crate::codec::response::{EncodedResponse, ResponseBody};
use crate::codec::{MetaView, OperationCodec};
use crate::route::TargetKind;

pub(super) type Item = Result<Event, SelectEventError>;

#[derive(Clone, Default)]
struct Counts {
    polls: Arc<AtomicUsize>,
    drops: Arc<AtomicUsize>,
}

impl Counts {
    fn totals(&self) -> [usize; 2] {
        [self.polls.load(Ordering::SeqCst), self.drops.load(Ordering::SeqCst)]
    }
}

struct Producer {
    items: VecDeque<Item>,
    counts: Counts,
    pending: bool,
    _send_only: Cell<()>,
}

impl Stream for Producer {
    type Item = Item;

    fn poll_next(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Option<Item>> {
        let this = self.get_mut();
        this.counts.polls.fetch_add(1, Ordering::SeqCst);
        if std::mem::take(&mut this.pending) {
            cx.waker().wake_by_ref();
            Poll::Pending
        } else {
            Poll::Ready(this.items.pop_front())
        }
    }
}

impl Drop for Producer {
    fn drop(&mut self) {
        self.counts.drops.fetch_add(1, Ordering::SeqCst);
    }
}

fn producer(items: Vec<Item>, pending: bool) -> (SelectEventStream, Counts) {
    let counts = Counts::default();
    let stream = SelectEventStream::new(Producer {
        items: items.into(),
        counts: counts.clone(),
        pending,
        _send_only: Cell::new(()),
    });
    (stream, counts)
}

fn response(payload: Option<SelectEventStream>) -> EncodedResponse {
    let request = http::Request::builder()
        .method("POST")
        .uri("http://localhost/bkt/key?select&select-type=2")
        .header("host", "localhost")
        .body(())
        .expect("fixture request");
    let request = WireRequest::accept(request, &Limits::default()).expect("accepted fixture");
    let view = MetaView::of(&request, TargetKind::Object).expect("fixture view");
    dto::SelectObjectContent::encode(dto::SelectObjectContentOutput { payload }, &view, 200).expect("Select response")
}

fn stream(response: EncodedResponse) -> ByteStream {
    match response.body {
        ResponseBody::Stream(stream) => stream,
        other => panic!("expected a live stream, got {other:?}"),
    }
}

fn poll_kind(result: Poll<Result<PayloadRead, StreamError>>) -> &'static str {
    match result {
        Poll::Pending => "pending",
        Poll::Ready(Ok(PayloadRead::Chunk(_))) => "chunk",
        Poll::Ready(Ok(PayloadRead::Eof { .. })) => "eof",
        Poll::Ready(Err(_)) => "error",
    }
}

#[test]
fn typed_responses_match_the_independent_oracle_bytes() {
    // Public s3s API at 5761ddfe4c509fcac87e3b99fd5bd9e176b442c0, Rust 1.97.1.
    // The retained fixture was independently decoded and both CRC ranges verified outside
    // this crate; expected bytes are never generated by the production encoder under test.
    let expected: Vec<_> = include_str!("wire-golden.txt")
        .lines()
        .map(|line| line.split_once('\t').expect("named hex fixture"))
        .map(|(name, hex)| (name.to_owned(), hex.to_owned()))
        .collect();
    let mut observed = Vec::new();
    for (name, items) in super::cases::cases() {
        let (events, _) = producer(items, false);
        let mut body = stream(response(Some(events)));
        let mut bytes = Vec::new();
        let mut cx = Context::from_waker(Waker::noop());
        loop {
            match Pin::new(&mut body).poll_read(&mut cx) {
                Poll::Ready(Ok(PayloadRead::Chunk(chunk))) => bytes.extend_from_slice(&chunk),
                Poll::Ready(Ok(PayloadRead::Eof { .. })) => break,
                other => panic!("immediate fixture {name}: {other:?}"),
            }
        }
        let mut hex = String::with_capacity(bytes.len() * 2);
        for byte in bytes {
            write!(hex, "{byte:02x}").expect("writing to a String cannot fail");
        }
        observed.push((name.to_owned(), hex));
    }
    assert_eq!(observed, expected);
}

#[test]
fn construction_pending_and_early_drop_do_not_prefetch() {
    let (events, counts) = producer(vec![Ok(Event::Cont(dto::ContinuationEvent {})), Ok(Event::End(dto::EndEvent {}))], true);
    let mut observations = vec![("constructed", counts.totals())];
    let mut body = stream(response(Some(events)));
    observations.push(("encoded", counts.totals()));
    let mut cx = Context::from_waker(Waker::noop());
    observations.push((poll_kind(Pin::new(&mut body).poll_read(&mut cx)), counts.totals()));
    observations.push((poll_kind(Pin::new(&mut body).poll_read(&mut cx)), counts.totals()));
    drop(body);
    observations.push(("dropped", counts.totals()));
    assert_eq!(
        observations,
        [
            ("constructed", [0, 0]),
            ("encoded", [0, 0]),
            ("pending", [1, 0]),
            ("chunk", [2, 0]),
            ("dropped", [2, 1])
        ]
    );
}

#[test]
fn absent_payload_and_an_empty_live_producer_remain_distinct() {
    let absent = response(None);
    let (events, counts) = producer(Vec::new(), false);
    let present = response(Some(events));
    let header_facts = (
        absent.status.as_u16(),
        present.status.as_u16(),
        absent.headers.contains_key(http::header::CONTENT_TYPE),
        present.headers.contains_key(http::header::CONTENT_TYPE),
        matches!(absent.body, ResponseBody::Empty),
        present.body.is_empty(),
    );
    let mut body = stream(present);
    let mut cx = Context::from_waker(Waker::noop());
    let first = poll_kind(Pin::new(&mut body).poll_read(&mut cx));
    let second = poll_kind(Pin::new(&mut body).poll_read(&mut cx));
    drop(body);
    assert_eq!(
        (header_facts, first, second, counts.totals()),
        ((200, 200, false, false, true, false), "eof", "error", [1, 1])
    );
}

#[test]
fn oversized_frames_are_refused_without_polling_the_next_event() {
    let maximum = super::super::MAX_PAYLOAD_BYTES;
    let cases = [
        (
            Ok(Event::Records(dto::RecordsEvent {
                payload: Some(Bytes::from(vec![0; maximum])),
            })),
            "chunk",
        ),
        (
            Ok(Event::Records(dto::RecordsEvent {
                payload: Some(Bytes::from(vec![0; maximum + 1])),
            })),
            "error",
        ),
        (Err(SelectEventError::new("x".repeat(65_535), "")), "chunk"),
        (Err(SelectEventError::new("x".repeat(65_536), "")), "error"),
        (Err(SelectEventError::new("InternalError", "x".repeat(65_536))), "error"),
        (Err(SelectEventError::new("x".repeat(65_535), "x".repeat(65_535))), "error"),
    ];
    for (item, expected) in cases {
        let (events, counts) = producer(vec![item, Ok(Event::End(dto::EndEvent {}))], false);
        let mut body = stream(response(Some(events)));
        let mut cx = Context::from_waker(Waker::noop());
        let first = poll_kind(Pin::new(&mut body).poll_read(&mut cx));
        let after_refusal = if expected == "error" {
            poll_kind(Pin::new(&mut body).poll_read(&mut cx))
        } else {
            "unpolled"
        };
        drop(body);
        assert_eq!(
            (first, after_refusal, counts.totals()),
            (expected, if expected == "error" { "error" } else { "unpolled" }, [1, 1])
        );
    }
}
