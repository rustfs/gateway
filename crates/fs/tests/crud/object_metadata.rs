/// Negative — a corrupted upload record refuses the completion instead of publishing without it.
///
/// The completion answers `NoSuchUpload` rather than the section's own diagnosis, because
/// `read_upload_record` maps every undecodable record to "this capability does not exist" and
/// predates this section. The diagnosis is not lost: `ListMultipartUploads` reads the same record
/// through the propagating path and fails closed there, which is asserted below so that the two
/// answers stay one decision rather than drifting into a completion that quietly publishes.
#[tokio::test]
async fn a_corrupted_upload_section_refuses_the_completion() {
    let root = TestRoot::new();
    let (_, running) = service(&root);
    create_bucket(&running, "broken-init").await;
    let upload = initiate_with_metadata(&running, "broken-init", "part.txt", &[("mtime", "9")]).await;
    let entity_tag = upload_part(&running, "broken-init", "part.txt", &upload, 1, b"assembled bytes").await;
    drop(running);

    let uploads = bucket_path(&root, "broken-init").join("uploads");
    let directory = std::fs::read_dir(&uploads)
        .expect("a readable upload directory")
        .flatten()
        .map(|entry| entry.path())
        .find(|path| path.is_dir())
        .expect("one upload directory");
    let record = std::fs::read_to_string(directory.join("record")).expect("the upload record");
    std::fs::write(directory.join("record"), record.replace("meta/1 1", "meta/2 1")).expect("a rewritable upload record");

    let (_, reopened) = service(&root);
    let completed = complete(&reopened, "broken-init", "part.txt", &upload, &[(1, &entity_tag)]).await;
    assert_eq!(completed.status(), 404, "{}", String::from_utf8_lossy(completed.body()));
    assert!(
        String::from_utf8_lossy(completed.body()).contains("NoSuchUpload"),
        "{}",
        String::from_utf8_lossy(completed.body())
    );
    assert_eq!(get(&reopened, "broken-init", "part.txt").await.status(), 404);
    let listed = exchange(&reopened, signed(http::Method::GET, "/broken-init?uploads", Bytes::new())).await;
    assert_eq!(listed.status(), 500, "{}", String::from_utf8_lossy(listed.body()));
}

/// Negative — a lifecycle transition rewrites the record and must not drop its metadata.
///
/// The transition is the one code path that re-encodes a record that already exists, so it is the
/// one place where the metadata can be lost without a client ever asking for it: the object keeps
/// its bytes, its entity tag and its version id, and only the metadata quietly disappears.
#[tokio::test]
async fn a_lifecycle_transition_does_not_drop_the_stored_metadata() {
    use super::lifecycle_transitions::{DUE, DUE_MD5, put_policy, transitioning_service};

    let root = TestRoot::new();
    let (_, initial) = service(&root);
    create_bucket(&initial, "cold").await;
    put_policy(&initial, "cold", DUE, DUE_MD5, None).await;
    assert_eq!(
        put_with_metadata(&initial, "cold", "report.txt", b"stamped", &[("mtime", "1767323045.5")])
            .await
            .status(),
        200
    );
    drop(initial);

    let (backend, transitioned) = transitioning_service(&root, SIGNED_AT_SECONDS + 1);
    assert_eq!(backend.transition_lifecycle_once().await.expect("a valid sweep"), 1);
    drop(transitioned);

    let (_, reopened) = service(&root);
    let read = get(&reopened, "cold", "report.txt").await;
    assert_eq!(read.status(), 200, "{}", String::from_utf8_lossy(read.body()));
    assert_eq!(
        header(&read, "x-amz-storage-class"),
        Some(&http::HeaderValue::from_static("STANDARD_IA")),
        "the transition must have happened for this to be evidence"
    );
    assert_eq!(returned_metadata(&read), [("mtime".to_owned(), "1767323045.5".to_owned())]);
}
