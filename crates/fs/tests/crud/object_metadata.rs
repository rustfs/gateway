/// Negative — metadata past the stored ceiling is refused, and no object is published.
#[tokio::test]
async fn oversized_metadata_is_refused_and_stores_nothing() {
    let root = TestRoot::new();
    let (_, running) = service(&root);
    create_bucket(&running, "oversized").await;
    let value = "v".repeat(2049 - "mtime".len());
    let response = put_with_metadata(&running, "oversized", "report.txt", b"stamped", &[("mtime", &value)]).await;
    assert_eq!(response.status(), 400, "{}", String::from_utf8_lossy(response.body()));
    assert!(
        String::from_utf8_lossy(response.body()).contains("MetadataTooLarge"),
        "{}",
        String::from_utf8_lossy(response.body())
    );
    assert_eq!(get(&running, "oversized", "report.txt").await.status(), 404);
    drop(running);

    let (_, reopened) = service(&root);
    assert_eq!(get(&reopened, "oversized", "report.txt").await.status(), 404);
}

