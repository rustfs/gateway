/// Negative — a record cut off inside a metadata entry fails closed rather than reading short.
///
/// The bytes stop mid-value, so the entry's hex is an odd number of digits. Nothing about the
/// object's own eight lines is wrong, which is the point: only the section decoder can catch this,
/// and a lenient hex read would hand back a truncated value as though it were the stored one.
#[tokio::test]
async fn a_record_truncated_inside_a_metadata_entry_fails_the_read_closed() {
    let root = TestRoot::new();
    let (_, running) = service(&root);
    create_bucket(&running, "cut").await;
    assert_eq!(
        put_with_metadata(&running, "cut", "report.txt", b"stamped", &[("mtime", "1767323045")])
            .await
            .status(),
        200
    );
    drop(running);
    let directory = only_version_directory(&root, "cut");
    let record = read_record(&directory);
    let cut = record.len().saturating_sub(2);
    write_record(&directory, record.get(..cut).expect("a record longer than two bytes"));

    let (_, reopened) = service(&root);
    let read = get(&reopened, "cut", "report.txt").await;
    assert_eq!(read.status(), 500, "{}", String::from_utf8_lossy(read.body()));
    assert_eq!(returned_metadata(&read), []);
    assert_ne!(read.body().as_ref(), b"stamped");
}

