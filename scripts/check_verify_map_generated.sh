#!/usr/bin/env bash
# REQUIRES-BUILD
set -euo pipefail

# =============================================================================
# check_verify_map_generated.sh
#
# WHAT THIS CHECKS
#   `xtask/verify-map.toml` and the handler macro operation-name table exist, carry
#   codegen ownership markers, and are byte-for-byte what `cargo xtask codegen --check`
#   regenerates in memory.
#
# WHY
#   rustfs/backlog#1743. `verify --op` must use a generated operation-to-test
#   mapping. A hand-maintained map silently stops running cases as operations
#   evolve, producing a fast but meaningless green verification loop.
#   rustfs/backlog#1702. The handler macro must consume the same generated
#   operation set as the route table, not a second hand-maintained whitelist.
#
# HOW TO EXEMPT
#   Not applicable. Change the model, overlay, or generator and regenerate the
#   map. Direct edits are always drift.
#
# USAGE
#   scripts/check_verify_map_generated.sh
#   GATEWAY_CHECK_ROOT=/path/to/repo scripts/check_verify_map_generated.sh
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="${GATEWAY_CHECK_ROOT:-$(cd "${SCRIPT_DIR}/.." && pwd)}"
MAP="$ROOT_DIR/xtask/verify-map.toml"
EXPECTED='# @generated by cargo xtask codegen; do not edit'
NAMES="$ROOT_DIR/crates/macros/src/op_names.rs"
NAMES_EXPECTED='// @generated by `cargo xtask codegen`. Do not edit.'

if [[ ! -f "$MAP" ]]; then
    printf 'check_verify_map_generated.sh: required generated input is missing: %s\n' "$MAP" >&2
    exit 1
fi

if [[ ! -f "$NAMES" ]]; then
    printf 'check_verify_map_generated.sh: required generated input is missing: %s\n' "$NAMES" >&2
    exit 1
fi

IFS= read -r first_line <"$MAP" || true
if [[ "$first_line" != "$EXPECTED" ]]; then
    printf 'check_verify_map_generated.sh: %s has no exact codegen ownership marker\n' "$MAP" >&2
    exit 1
fi

if ! grep -Fqx "$NAMES_EXPECTED" "$NAMES"; then
    printf 'check_verify_map_generated.sh: %s has no exact codegen ownership marker\n' "$NAMES" >&2
    exit 1
fi

SOURCE_MAP="$(cd "${SCRIPT_DIR}/.." && pwd)/xtask/verify-map.toml"
SOURCE_NAMES="$(cd "${SCRIPT_DIR}/.." && pwd)/crates/macros/src/op_names.rs"
if [[ "$MAP" != "$SOURCE_MAP" ]] && ! cmp -s "$SOURCE_MAP" "$MAP"; then
    printf 'check_verify_map_generated.sh: verify-map drifted from the tested baseline\n' >&2
    exit 1
fi
if [[ "$NAMES" != "$SOURCE_NAMES" ]] && ! cmp -s "$SOURCE_NAMES" "$NAMES"; then
    printf 'check_verify_map_generated.sh: crates/macros/src/op_names.rs drifted from the tested baseline\n' >&2
    exit 1
fi

# IR validation deliberately carries a full draft 2020-12 implementation. This guard exercises
# only codegen, so keep that unrelated dependency out of its cold CI build.
if ! (cd "$ROOT_DIR" && "${CARGO:-cargo}" run --quiet --package xtask --no-default-features -- codegen --check); then
    printf 'check_verify_map_generated.sh: verify-map drifted; regenerate with `cargo xtask codegen`\n' >&2
    exit 1
fi

printf 'OK: operation verification tables are generated and current\n'
